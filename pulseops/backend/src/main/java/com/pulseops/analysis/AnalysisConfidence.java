package com.pulseops.analysis;

/**
 * AI 분석이 자기 가설을 얼마나 믿는지를 나타낸다.
 * <p>
 * 숫자가 아니라 세 단계이다. 확률을 내놓게 하면 0.83 같은 값이 나오는데, 그 두 자리를 만든 근거가
 * 이 분석에는 없다. Claude가 보는 것은 창 하나의 요청 수와 오류율과 P95뿐이며, 그것으로 원인의
 * 확률을 계산할 방법은 존재하지 않는다. 없는 정밀도를 숫자로 적으면 읽는 사람은 그것을 계산된 값으로
 * 읽는다.
 * <p>
 * 세 단계로 좁히면 값의 뜻도 사람이 정할 수 있다. LOW는 근거가 이 가설을 특별히 지지하지 않는다는
 * 뜻이고, HIGH는 주어진 관측만으로도 다른 설명을 찾기 어렵다는 뜻이다. 이것은 정답률이 아니라
 * 근거의 두께에 대한 표시이다.
 */
public enum AnalysisConfidence {

	LOW,
	MEDIUM,
	HIGH

}
